const lighten = (hex: string, k: number) => {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v: number) => Math.min(255, Math.round(v + (255 - v) * k));
  return `rgb(${ch(n >> 16)},${ch((n >> 8) & 255)},${ch(n & 255)})`;
};

/** size×size 영역 가운데에 아이템 임시 그림을 그린다. 그릴 수 없으면 false. */
export function drawTempIcon(itemId: string, x: number, y: number, size: number): boolean {
  const d = PIECES[itemId];
  if (!d) return false;
  const key = d.equip ? (ICONS[d.equip.type] ? d.equip.type : d.equip.slot === "body" ? "옷" : d.equip.slot === "bag" ? "가방" : d.equip.slot === "acc" ? "반지" : "한손검") : d.kind;
  const rows = ICONS[key] ?? ICONS.material;
  const main = PIECE[d.color] ?? C.sub;
  const accent = lighten(d.elements[0] ? PIECE[d.elements[0]] : main, 0.35);
  const px = Math.floor(size / 16), ox = x + Math.floor((size - px * 16) / 2), oy = y + Math.floor((size - px * 16) / 2);
  rows.forEach((row, r) =>
    [...row].forEach((ch, c) => {
      if (ch === " ") return;
      R(ox + c * px, oy + r * px + px, px, px, ch === "." ? "#1A1712" : ch === "+" ? accent : main);
    })
  );
  return true;
}
