// 던전 DB — 던전·층·구획 정보는 전부 여기 한 곳. 맵을 설계할 때 넣는 데이터 (docs/exploration.md).
// data/monsters.ts처럼 순수 데이터: 함수·클래스 없음, 다른 데이터는 id 문자열로만 가리킨다
//   (몬스터 = MONSTER_DB id, 소재·아이템 = PIECES id, 타일 풀 = DECKS 이름, 채집지 = GATHER_KINDS 키).
// 고정: 층·구획 모양, 서식지(출현 몬스터·채집지), 채집·보물상자·휴식 위치. 원정마다 바뀌는 것은 타일 순서와 타일에 붙는 심볼뿐.
// 구획을 고치면 `node tools/check-dungeons.mjs`로 도달성을 확인한다.
// 좌표는 구획 안의 칸 [열, 행]. 구획 모양은 문자열 격자: '.' 빈 칸, '#' 바위(못 놓음), ' ' 구획 밖.
import type { EnemySize, GatherKind } from "./explore";
import type { Cell } from "./pieces";

export type Side = "top" | "bottom" | "left" | "right";

/**
 * 입구·출구. 구획 틀 바깥으로 한 칸 튀어나온 자리이고, cell은 그 바깥 칸 좌표다 (-1이나 폭·높이와 같은 값이 될 수 있다).
 * side 쪽 안쪽 칸이 연결 지점 — 입구는 거기서부터 타일을 잇기 시작하고, 출구는 거기까지 닿아야 지나갈 수 있다.
 */
export interface ExitDef {
  cell: Cell;
  side: Side;
}
export interface DoorDef extends ExitDef {
  /** 이어진 구획 id */
  to: string;
}

export interface GatherPoint {
  cell: Cell;
  kind: GatherKind;
}

export interface ChestPoint {
  /** 한 번 열면 다음 원정부터 사라진다 — 전체에서 고유한 id */
  id: string;
  cell: Cell;
  item: string;
}

/** 길 타일에 심볼이 붙는 비율 (타일 칸마다 따로 굴림) */
export interface PieceSymbolRates {
  enemy: number;
  item: number;
  /** 적 심볼 크기 가중치 */
  /** 옛 심볼 크기 비율 — 2026-11-08부터 안 쓴다 (적 심볼은 1칸 하나, 팀은 power로) */
  sizes?: Partial<Record<EnemySize, number>>;
  /** 아이템 심볼에서 나오는 것 (PIECES id) */
  loot: string[];
}

export interface DistrictDef {
  id: string;
  name: string;
  /** 서식지 한 줄 설명 */
  habitat: string;
  /** 구획 테두리·미니맵 색 */
  color: string;
  /** 미니맵(아이작식 격자)에서의 자리 */
  pos: Cell;
  shape: string[];
  doors: DoorDef[];
  /** 층에 처음 들어올 때의 입구 (층 입구 구획만) */
  start?: ExitDef;
  /** 내려가는 계단 (있는 구획만) */
  stairs?: ExitDef;
  /** 출현 가능한 몬스터 (MONSTER_DB id) */
  monsters: string[];
  /** 이 구획의 중간 보스 (MONSTER_DB id). 탐색 등장 방식은 TODO(spec) — 지금은 적어 두기만 한다 */
  midBoss?: string;
  /** 채집지 견본 (2026-11-08): 종류·비율만 쓴다. 실제 자리와 개수는 원정마다 무작위 (d01Explore rollGathers).
   *  개수 = gatherCount 범위, 없으면 견본 수 × 1.5 안팎. 미니맵에는 종류만 보인다 */
  gathers: GatherPoint[];
  gatherCount?: [number, number];
  /** 채집지 종류별 드롭 표 [소재 id, 확률 %] (docs/dungeon-themes.md, tools/gen_district_loot.py). 없으면 GATHER_KINDS 기본 */
  gatherLoot?: Partial<Record<GatherKind, Array<[string, number]>>>;
  /** 보물상자 (한 번만). 중요 아이템(kind "key")은 전리품 분배 없이 바로 창고로 */
  chests: ChestPoint[];
  /** 휴식 포인트 (원정마다 한 번, 체류 시간 +) */
  rests: Cell[];
  symbols: PieceSymbolRates;
  /** 적 팀 전투력 범위 [최소, 최대] — 한 전투의 몬스터 전투력(MonsterRecord.power) 합이 이 안에서 정해진다 (docs/monsters.md 5장 적 팀) */
  power: [number, number];
  /** 길 타일 풀 (DECKS 이름) */
  deck: string;
  /** 전투 배경 (public/backgrounds/battle_<이름>.webp). 없으면 cave (2026-11-09) */
  battleBg?: string;
}

export interface FloorDef {
  id: string;
  name: string;
  depth: number;
  startDistrict: string;
  districts: DistrictDef[];
}

export interface DungeonDef {
  id: string;
  name: string;
  floors: FloorDef[];
}

